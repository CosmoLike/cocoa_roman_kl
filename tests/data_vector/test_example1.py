"""Unit tests 1-4: the cosmic-shear likelihood on the frozen test data.

Cosmic shear is the correlation of galaxy shape distortions produced by
weak gravitational lensing; in this Fourier-space project its data
vector holds the shear angular power spectra C_l^ss of every source-bin
pair in 20 multipole bands (l = 20 to 4000). The tests evaluate the
roman_kl.cosmic_shear likelihood on the frozen copy of example1's
configuration: a complete configuration and data set stored under
tests/frozen/ and pinned by a SHA-256 manifest, so edits to the live
example files cannot change what the tests evaluate (the docstring of
cocoa_test_utils.py says more). The NLA tests evaluate a synthetic data
vector generated by the same model at the fiducial point, so the frozen
reference chi2 is zero up to rounding. The four tests:

  1. chi2 at the frozen fiducial point, within CHI2_TOLERANCE (0.2) of
     the frozen reference value.
  2. race check: on one model, the fiducial evaluated fresh and again
     as the 10th of 10 cosmologies in a row must agree to
     RACE_TOLERANCE (1e-4). A disagreement means state leaked between
     evaluations or OpenMP threads raced.
  3. the same comparison as test 1 with the TATT intrinsic-alignment
     model (IA_model: 1) and ROMAN_KL_A2_1 = 0.05, ROMAN_KL_BTA_1 = 0.05,
     ROMAN_KL_A2_2 = -1.51541 replacing the NLA point's zeros, against a
     TATT-generated data vector. A1 is fixed to 0 in this configuration,
     so the NLA tests carry no intrinsic alignment and under TATT only
     the tidal-torquing A2 terms contribute (the B_TA terms multiply A1).
  4. the same race check as test 2 with the TATT model.

To run (from the Cocoa/ folder, cocoa environment active,
start_cocoa.sh sourced):

    python -m pytest ./projects/roman_kl/tests/data_vector
"""

import os

# OpenMP reads OMP_NUM_THREADS when the compiled libraries load, so
# this must run before any cobaya/cosmolike import in the process.
os.environ["OMP_NUM_THREADS"] = "4"

import sys
import unittest

# The tests folder is not a package; put it on the import path so the
# shared harness resolves no matter where pytest was launched from.
sys.path.insert(0, os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
import cocoa_test_utils as u

# The shared factory (cosmolike_core/cocoa_testing_suites.py) builds
# the chi2 + race test class for one frozen example; assigning its
# return value to the usual module-level name is what makes pytest
# collect it here, with unchanged test ids. The numbers name the
# methods and the printed reports; the label opens every report line.
TestExample1CosmicShear = u.example_suite(
    u, name="TestExample1CosmicShear", example="example1",
    label="example1 (cosmic shear",
    numbers=("1", "2"), tatt_numbers=("3", "4"))

# __name__ is "__main__" only when this file runs directly as a
# script; pytest imports the module instead, so this block stays
# idle under pytest
if __name__ == "__main__":
    unittest.main(verbosity=2)
